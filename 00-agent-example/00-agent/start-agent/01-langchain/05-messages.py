

# Messages are the fundamental unit of context for models in LangChain. They represent the input and output of models,
# carrying both the content and metadata needed to represent the state of a conversation when interacting with an LLM.
# Messages are objects that contain:
#  Role - Identifies the message type (e.g. system, user)
#  Content - Represents the actual content of the message (like text, images, audio, documents, etc.)
#  Metadata - Optional fields such as response information, message IDs, and token usage
# LangChain provides a standard message type that works across all model providers,
# ensuring consistent behavior regardless of the model being called.



# 1，基本用法

from langchain.chat_models import init_chat_model
from langchain.messages import HumanMessage, AIMessage, SystemMessage

model = init_chat_model("gpt-5-nano")

system_msg = SystemMessage("You are a helpful assistant.")
human_msg = HumanMessage("Hello, how are you?")

# Use with chat models
messages = [system_msg, human_msg]
response = model.invoke(messages)  # Returns AIMessage


# 1.1，Text prompts
response = model.invoke("Write a haiku about spring")


# 1.2，Message prompts
from langchain.messages import SystemMessage, HumanMessage, AIMessage

messages = [
    SystemMessage("You are a poetry expert"),
    HumanMessage("Write a haiku about spring"),
    AIMessage("Cherry blossoms bloom...")
]
response = model.invoke(messages)

# 1.3，Dictionary format
# You can also specify messages directly in OpenAI chat completions format.

messages = [
    {"role": "system", "content": "You are a poetry expert"},
    {"role": "user", "content": "Write a haiku about spring"},
    {"role": "assistant", "content": "Cherry blossoms bloom..."}
]
response = model.invoke(messages)

# 2，消息类型

#  System message - Tells the model how to behave and provide context for interactions
#  Human message - Represents user input and interactions with the model
#  AI message - Responses generated by the model, including text content, tool calls, and metadata
#  Tool message - Represents the outputs of tool calls


# 2.1，System message
# A SystemMessage represent an initial set of instructions that primes the model’s behavior.
# You can use a system message to set the tone, define the model’s role, and establish guidelines for responses.

system_msg = SystemMessage("You are a helpful coding assistant.")

messages = [
    system_msg,
    HumanMessage("How do I create a REST API?")
]
response = model.invoke(messages)


from langchain.messages import SystemMessage, HumanMessage

system_msg = SystemMessage("""
You are a senior Python developer with expertise in web frameworks.
Always provide code examples and explain your reasoning.
Be concise but thorough in your explanations.
""")

messages = [
    system_msg,
    HumanMessage("How do I create a REST API?")
]
response = model.invoke(messages)


# 2.2，Human message
# A HumanMessage represents user input and interactions. They can contain text, images, audio, files, and any other amount of multimodal content.
# When an agent adds a human message that the user did not type, such as a conversation summary, it can mark the message with notification metadata.

response = model.invoke([
  HumanMessage("What is machine learning?")
])

human_msg = HumanMessage(
    content="Hello!",
    name="alice",  # Optional: identify different users
    id="msg_123",  # Optional: unique identifier for tracing
)



# 2.3，AI message
# An AIMessage represents the output of a model invocation.
# They can include multimodal data, tool calls, and provider-specific metadata that you can later access.

response = model.invoke("Explain AI")
print(type(response))  # <class 'langchain.messages.AIMessage'>

# AIMessage objects are returned by the model when calling it,
# which contains all of the associated metadata in the response.
# Providers weigh/contextualize types of messages differently,
# which means it is sometimes helpful to manually create a new AIMessage object and insert it into the message history as if it came from the model.
from langchain.messages import AIMessage, SystemMessage, HumanMessage

# Create an AI message manually (e.g., for conversation history)
ai_msg = AIMessage("I'd be happy to help you with that question!")

# Add to conversation history
messages = [
    SystemMessage("You are a helpful assistant"),
    HumanMessage("Can you help me?"),
    ai_msg,  # Insert as if it came from the model
    HumanMessage("Great! What's 2+2?")
]

response = model.invoke(messages)


# 2.3.1，Tool calls
# When models make tool calls, they’re included in the AIMessage:
from langchain.chat_models import init_chat_model

model = init_chat_model("gpt-5-nano")

def get_weather(location: str) -> str:
    """Get the weather at a location."""
    ...

model_with_tools = model.bind_tools([get_weather])
response = model_with_tools.invoke("What's the weather in Paris?")

for tool_call in response.tool_calls:
    print(f"Tool: {tool_call['name']}")
    print(f"Args: {tool_call['args']}")
    print(f"ID: {tool_call['id']}")